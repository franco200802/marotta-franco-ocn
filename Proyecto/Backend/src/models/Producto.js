class Producto {
  constructor(codigo, nombre, categoria, talle, color, descripcion, precio, stock, imagen) {
    this.codigo = codigo;
    this.nombre = nombre;
    this.categoria = categoria;
    this.talle = talle;
    this.color = color;
    this.descripcion = descripcion;
    this.precio = precio;
    this.stock = stock;
    this.imagen = imagen;
  }
}

export default Producto;
